-- ============================================================================

-- 1. Movies Catalog
CREATE TABLE IF NOT EXISTS public.movies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    duration_minutes INTEGER NOT NULL CHECK (duration_minutes > 0),
    language TEXT NOT NULL,
    genre TEXT NOT NULL,
    certification TEXT NOT NULL DEFAULT 'UA',
    release_date DATE NOT NULL DEFAULT CURRENT_DATE,
    poster_url TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Showtimes (Venue + Screen + Schedule + Base Price)
CREATE TABLE IF NOT EXISTS public.showtimes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id BIGINT NOT NULL REFERENCES public.movies(id) ON DELETE CASCADE,
    theater_name TEXT NOT NULL,
    theater_city TEXT NOT NULL DEFAULT 'Chennai',
    theater_address TEXT NOT NULL DEFAULT '',
    screen_name TEXT NOT NULL,
    screen_type TEXT NOT NULL CHECK (screen_type IN ('2D', '3D', 'IMAX')),
    show_date DATE NOT NULL DEFAULT CURRENT_DATE,
    start_time TEXT NOT NULL,
    end_time TEXT NOT NULL DEFAULT '',
    base_price NUMERIC(10, 2) NOT NULL CHECK (base_price >= 0),
    status TEXT NOT NULL DEFAULT 'SCHEDULED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_showtimes_movie_id ON public.showtimes(movie_id);

-- 3. Bookings (Stores seat bookings per showtime)
CREATE TABLE IF NOT EXISTS public.bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_reference TEXT NOT NULL UNIQUE,
    showtime_id BIGINT NOT NULL REFERENCES public.showtimes(id) ON DELETE RESTRICT,
    seat_codes TEXT[] NOT NULL CHECK (array_length(seat_codes, 1) BETWEEN 1 AND 6),
    customer_name TEXT NOT NULL,
    customer_email TEXT NOT NULL,
    customer_phone TEXT NOT NULL,
    tickets_subtotal NUMERIC(10, 2) NOT NULL DEFAULT 0,
    convenience_fee NUMERIC(10, 2) NOT NULL DEFAULT 30.00,
    total_amount NUMERIC(10, 2) NOT NULL CHECK (total_amount >= 0),
    booking_status TEXT NOT NULL DEFAULT 'CONFIRMED' CHECK (booking_status IN ('CONFIRMED', 'CANCELLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_bookings_showtime_status ON public.bookings(showtime_id, booking_status);

-- ============================================================================
-- Atomic Double-Booking Prevention Trigger (Concurrency Control in Postgres)
-- ============================================================================

CREATE OR REPLACE FUNCTION public.prevent_double_booking()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    conflicting_seats TEXT[];
BEGIN
    IF NEW.booking_status <> 'CONFIRMED' THEN
        RETURN NEW;
    END IF;

    -- Serialize concurrent inserts for the same showtime
    PERFORM pg_advisory_xact_lock(NEW.showtime_id);

    SELECT ARRAY_AGG(DISTINCT existing_seat)
    INTO conflicting_seats
    FROM public.bookings b,
         LATERAL unnest(b.seat_codes) AS existing_seat
    WHERE b.showtime_id = NEW.showtime_id
      AND b.booking_status = 'CONFIRMED'
      AND existing_seat = ANY(NEW.seat_codes);

    IF conflicting_seats IS NOT NULL AND array_length(conflicting_seats, 1) > 0 THEN
        RAISE EXCEPTION 'Seats already booked: %', array_to_string(conflicting_seats, ', ')
            USING ERRCODE = '23505';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_prevent_double_booking ON public.bookings;
CREATE TRIGGER trg_prevent_double_booking
BEFORE INSERT ON public.bookings
FOR EACH ROW
EXECUTE FUNCTION public.prevent_double_booking();

-- ============================================================================
-- Row Level Security (RLS) for Publishable Key Client Access
-- ============================================================================

ALTER TABLE public.movies ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.showtimes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bookings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public read movies" ON public.movies;
CREATE POLICY "Public read movies" ON public.movies
    FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public read showtimes" ON public.showtimes;
CREATE POLICY "Public read showtimes" ON public.showtimes
    FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public read bookings" ON public.bookings;
CREATE POLICY "Public read bookings" ON public.bookings
    FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public create bookings" ON public.bookings;
CREATE POLICY "Public create bookings" ON public.bookings
    FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Public cancel bookings" ON public.bookings;
CREATE POLICY "Public cancel bookings" ON public.bookings
    FOR UPDATE USING (true) WITH CHECK (booking_status IN ('CONFIRMED', 'CANCELLED'));

